-- 1. BỔ SUNG CỘT CHO BẢNG HÓA ĐƠN (INVOICES)
ALTER TABLE INVOICES ADD (
    Status        VARCHAR2(20)  DEFAULT 'COMPLETED' NOT NULL CHECK (Status IN ('COMPLETED', 'CANCELLED')),
    CancelledBy   VARCHAR2(50),
    CancelledDate TIMESTAMP,
    CancelReason  VARCHAR2(500),
    CONSTRAINT FK_INVOICES_CANCELLED_BY FOREIGN KEY (CancelledBy) REFERENCES USERS(id)
);

CREATE INDEX IDX_INVOICES_STATUS ON INVOICES(Status);

-- 2. BỔ SUNG CỘT CHO BẢNG CHỮ KÝ SỐ (DIGITAL_SIGNATURES)
ALTER TABLE DIGITAL_SIGNATURES ADD (
    Status        VARCHAR2(20)  DEFAULT 'VALID' NOT NULL CHECK (Status IN ('VALID', 'REVOKED')),
    RevokedAt     TIMESTAMP,
    RevokedReason VARCHAR2(500)
);

CREATE INDEX IDX_SIGNATURES_STATUS ON DIGITAL_SIGNATURES(Status);

-- 3. CẬP NHẬT CHECK CONSTRAINT CHO BẢNG LỊCH SỬ BIẾN ĐỘNG TỒN KHO (INVENTORY_TRANSACTIONS)
-- Cho phép thêm loại giao dịch 'HOAN_HUY' khi hủy hóa đơn bán lẻ
DECLARE
    v_constraint_name VARCHAR2(100);
BEGIN
    SELECT CONSTRAINT_NAME INTO v_constraint_name
    FROM USER_CONSTRAINTS
    WHERE TABLE_NAME = 'INVENTORY_TRANSACTIONS'
      AND SEARCH_CONDITION_VC LIKE '%TransactionType%'
      AND ROWNUM = 1;

    EXECUTE IMMEDIATE 'ALTER TABLE INVENTORY_TRANSACTIONS DROP CONSTRAINT ' || v_constraint_name;
    EXECUTE IMMEDIATE 'ALTER TABLE INVENTORY_TRANSACTIONS ADD CONSTRAINT CHK_INV_TX_TYPE CHECK (TransactionType IN (''NHAP'', ''XUAT_BAN'', ''DIEU_CHINH'', ''TRA_HANG'', ''HOAN_HUY'', ''XUAT_DIEU_CHUYEN'', ''NHAP_DIEU_CHUYEN''))';
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        EXECUTE IMMEDIATE 'ALTER TABLE INVENTORY_TRANSACTIONS ADD CONSTRAINT CHK_INV_TX_TYPE CHECK (TransactionType IN (''NHAP'', ''XUAT_BAN'', ''DIEU_CHINH'', ''TRA_HANG'', ''HOAN_HUY'', ''XUAT_DIEU_CHUYEN'', ''NHAP_DIEU_CHUYEN''))';
    WHEN OTHERS THEN
        NULL;
END;
/
