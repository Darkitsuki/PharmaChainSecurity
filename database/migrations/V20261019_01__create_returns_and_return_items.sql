-- 1. BẢNG PHIẾU ĐỔI TRẢ HÀNG (RETURNS)
CREATE TABLE RETURNS (
    id                VARCHAR2(50)     NOT NULL,
    ReturnNo          VARCHAR2(50)     NOT NULL,
    InvoiceId         VARCHAR2(50)     NOT NULL,
    BranchId          VARCHAR2(50)     NOT NULL,
    CashierId         VARCHAR2(50)     NOT NULL,
    CustomerId        VARCHAR2(50),
    TotalRefundAmount NUMBER(15, 2)    DEFAULT 0.00 NOT NULL CHECK (TotalRefundAmount >= 0),
    Reason            VARCHAR2(500)    NOT NULL,
    Status            VARCHAR2(20)     DEFAULT 'COMPLETED' NOT NULL CHECK (Status IN ('COMPLETED', 'REJECTED')),
    CreatedDate       TIMESTAMP        DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_RETURNS PRIMARY KEY (id),
    CONSTRAINT UQ_RETURNS_NO UNIQUE (ReturnNo),
    CONSTRAINT FK_RETURNS_INVOICES FOREIGN KEY (InvoiceId) REFERENCES INVOICES(id),
    CONSTRAINT FK_RETURNS_BRANCHES FOREIGN KEY (BranchId) REFERENCES BRANCHES(id),
    CONSTRAINT FK_RETURNS_CASHIER FOREIGN KEY (CashierId) REFERENCES USERS(id),
    CONSTRAINT FK_RETURNS_CUSTOMERS FOREIGN KEY (CustomerId) REFERENCES CUSTOMERS(id)
);

CREATE INDEX IDX_RETURNS_INVOICE ON RETURNS(InvoiceId);
CREATE INDEX IDX_RETURNS_BRANCH ON RETURNS(BranchId);
CREATE INDEX IDX_RETURNS_DATE ON RETURNS(CreatedDate);

-- 2. BẢNG CHI TIẾT HÀNG TRẢ (RETURN_ITEMS)
CREATE TABLE RETURN_ITEMS (
    ReturnId    VARCHAR2(50)     NOT NULL,
    DrugId      VARCHAR2(50)     NOT NULL,
    BatchId     VARCHAR2(50)     NOT NULL,
    Quantity    NUMBER(10)       NOT NULL CHECK (Quantity > 0),
    RefundPrice NUMBER(15, 2)    NOT NULL CHECK (RefundPrice >= 0),
    SubTotal    NUMBER(15, 2)    NOT NULL CHECK (SubTotal >= 0),
    ActionType  VARCHAR2(20)     DEFAULT 'RESTOCK' NOT NULL CHECK (ActionType IN ('RESTOCK', 'DISCARD')),
    CONSTRAINT PK_RETURN_ITEMS PRIMARY KEY (ReturnId, DrugId, BatchId),
    CONSTRAINT FK_RETITEMS_RETURNS FOREIGN KEY (ReturnId) REFERENCES RETURNS(id),
    CONSTRAINT FK_RETITEMS_DRUGS FOREIGN KEY (DrugId) REFERENCES DRUGS(id),
    CONSTRAINT FK_RETITEMS_BATCHES FOREIGN KEY (BatchId) REFERENCES DRUG_BATCHES(id)
);

CREATE INDEX IDX_RETITEMS_DRUG ON RETURN_ITEMS(DrugId);
CREATE INDEX IDX_RETITEMS_BATCH ON RETURN_ITEMS(BatchId);
