-- 1. BẢNG PHIẾU ĐIỀU CHUYỂN KHO LIÊN CHI NHÁNH (STOCK_TRANSFERS)
CREATE TABLE STOCK_TRANSFERS (
    id                   VARCHAR2(50)     NOT NULL,
    TransferNo           VARCHAR2(50)     NOT NULL,
    FromBranchId         VARCHAR2(50)     NOT NULL,
    ToBranchId           VARCHAR2(50)     NOT NULL,
    CreatedBy            VARCHAR2(50)     NOT NULL,
    ShippedBy            VARCHAR2(50),
    ReceivedBy           VARCHAR2(50),
    Status               VARCHAR2(20)     DEFAULT 'PENDING' NOT NULL CHECK (Status IN ('PENDING', 'IN_TRANSIT', 'COMPLETED', 'CANCELLED')),
    TotalItemsCount      NUMBER(10)       DEFAULT 0 NOT NULL CHECK (TotalItemsCount >= 0),
    TotalQuantity        NUMBER(10)       DEFAULT 0 NOT NULL CHECK (TotalQuantity >= 0),
    ShippedDate          TIMESTAMP,
    ReceivedDate         TIMESTAMP,
    Notes                VARCHAR2(500),
    CreatedDate          TIMESTAMP        DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_STOCK_TRANSFERS PRIMARY KEY (id),
    CONSTRAINT UQ_STOCK_TRANSFERS_NO UNIQUE (TransferNo),
    CONSTRAINT FK_TRANSFERS_FROM_BRANCH FOREIGN KEY (FromBranchId) REFERENCES BRANCHES(id),
    CONSTRAINT FK_TRANSFERS_TO_BRANCH FOREIGN KEY (ToBranchId) REFERENCES BRANCHES(id),
    CONSTRAINT FK_TRANSFERS_CREATED_BY FOREIGN KEY (CreatedBy) REFERENCES USERS(id),
    CONSTRAINT FK_TRANSFERS_SHIPPED_BY FOREIGN KEY (ShippedBy) REFERENCES USERS(id),
    CONSTRAINT FK_TRANSFERS_RECEIVED_BY FOREIGN KEY (ReceivedBy) REFERENCES USERS(id),
    CONSTRAINT CHK_TRANSFERS_DIFF_BRANCH CHECK (FromBranchId != ToBranchId)
);

CREATE INDEX IDX_TRANSFERS_FROM_BRANCH ON STOCK_TRANSFERS(FromBranchId);
CREATE INDEX IDX_TRANSFERS_TO_BRANCH ON STOCK_TRANSFERS(ToBranchId);
CREATE INDEX IDX_TRANSFERS_STATUS ON STOCK_TRANSFERS(Status);
CREATE INDEX IDX_TRANSFERS_DATE ON STOCK_TRANSFERS(CreatedDate);

-- 2. BẢNG CHI TIẾT MẶT HÀNG ĐIỀU CHUYỂN (STOCK_TRANSFER_ITEMS)
CREATE TABLE STOCK_TRANSFER_ITEMS (
    TransferId           VARCHAR2(50)     NOT NULL,
    DrugId               VARCHAR2(50)     NOT NULL,
    BatchId              VARCHAR2(50)     NOT NULL,
    Quantity             NUMBER(10)       NOT NULL CHECK (Quantity > 0),
    Notes                VARCHAR2(255),
    CONSTRAINT PK_STOCK_TRANSFER_ITEMS PRIMARY KEY (TransferId, DrugId, BatchId),
    CONSTRAINT FK_TRANSFER_ITEMS_TRANSFER FOREIGN KEY (TransferId) REFERENCES STOCK_TRANSFERS(id) ON DELETE CASCADE,
    CONSTRAINT FK_TRANSFER_ITEMS_DRUG FOREIGN KEY (DrugId) REFERENCES DRUGS(id),
    CONSTRAINT FK_TRANSFER_ITEMS_BATCH FOREIGN KEY (BatchId) REFERENCES DRUG_BATCHES(id)
);

CREATE INDEX IDX_TRANSFER_ITEMS_DRUG ON STOCK_TRANSFER_ITEMS(DrugId);
CREATE INDEX IDX_TRANSFER_ITEMS_BATCH ON STOCK_TRANSFER_ITEMS(BatchId);
